export function projectGapPaths() {
  const paths = teamCompletionPaths(projectGapOperations, {
    prefix: 'projectGap',
    tag: 'projects',
    description:
      'Current authorized Projects gap closure result; independent scope, retention and lifecycle fences apply.',
  });
  const download = paths[
    '/api/v1' + p + '/files/{fileId}/versions/{versionId}/download'
  ]!.get as { responses: Record<string, { content: unknown }> };
  download.responses['200']!.content = {
    'application/octet-stream': {
      schema: { type: 'string', format: 'binary' },
    },
  };
  return paths;
}
